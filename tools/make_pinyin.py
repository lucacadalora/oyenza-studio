#!/usr/bin/env python3
"""Generate crates/poni-core/src/romanize/pinyin_data.rs from the Unihan database.

Usage:
    curl -O https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
    unzip Unihan.zip -d unihan
    python3 tools/make_pinyin.py unihan

Reads the kMandarin field (first value = the most customary reading) for
U+3400-U+4DBF, U+4E00-U+9FFF and U+F900-U+FAFF. Compatibility ideographs
without their own reading take the reading of their kCompatibilityVariant.
Writes a deduplicated syllable list (most common first, so the index table
stays short) and one u16 per code point. Python 3 standard library only.
"""

import collections
import datetime
import os
import sys

BLOCKS = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF)]
SOURCE = "https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip"
PER_LINE = 32


def fields(path, wanted):
    """Yield (code point, value) for each line of `path` whose field is `wanted`."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cp, field, value = line.rstrip("\n").split("\t", 2)
            if field == wanted:
                yield int(cp[2:], 16), value


def header(path):
    """The `# Date:` and `# Unicode Version` lines at the top of a Unihan file."""
    date = version = "?"
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("#"):
                break
            if line.startswith("# Date:"):
                date = line[len("# Date:"):].split()[0]
            elif line.startswith("# Unicode Version"):
                version = line[len("# Unicode Version"):].strip()
    return date, version


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    readings_txt = os.path.join(src, "Unihan_Readings.txt")
    mandarin = {cp: v.split()[0] for cp, v in fields(readings_txt, "kMandarin")}
    compat = {}
    for name in ("Unihan_IRGSources.txt", "Unihan_Variants.txt"):
        path = os.path.join(src, name)
        if os.path.exists(path):
            for cp, v in fields(path, "kCompatibilityVariant"):
                compat[cp] = int(v.split()[0][2:], 16)

    reading = {}
    for first, last in BLOCKS:
        for cp in range(first, last + 1):
            r = mandarin.get(cp) or mandarin.get(compat.get(cp, -1))
            if r:
                reading[cp] = r

    counts = collections.Counter(reading.values())
    syllables = sorted(counts, key=lambda s: (-counts[s], s))
    index = {s: i + 1 for i, s in enumerate(syllables)}
    total = sum(last - first + 1 for first, last in BLOCKS)

    date, version = header(readings_txt)
    today = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    out = []
    out.append("//! Mandarin readings for CJK ideographs. Generated by `tools/make_pinyin.py`;")
    out.append("//! do not edit by hand, rerun the script instead.")
    out.append("//!")
    out.append(f"//! Source: Unicode Unihan database {version} ({SOURCE}),")
    out.append(f"//! Unihan_Readings.txt dated {date}, field kMandarin (first value);")
    out.append("//! compatibility ideographs read as their kCompatibilityVariant.")
    out.append(f"//! Generated {today}. Data under the Unicode License v3:")
    out.append("//! https://www.unicode.org/license.txt")
    out.append("")
    out.append(f"/// Distinct readings ({len(syllables)}), most common first.")
    out.append("#[rustfmt::skip]")
    out.append(f"pub(super) static SYLLABLES: [&str; {len(syllables)}] = [")
    row = []
    for s in syllables:
        row.append(f'"{s}",')
        if len(row) == 16:
            out.append("    " + " ".join(row))
            row = []
    if row:
        out.append("    " + " ".join(row))
    out.append("];")
    out.append("")
    out.append("/// Code point ranges in `INDEX`: (first, last, offset of `first` in `INDEX`).")
    out.append(f"pub(super) const BLOCKS: [(u32, u32, usize); {len(BLOCKS)}] = [")
    offset = 0
    for first, last in BLOCKS:
        out.append(f"    (0x{first:04X}, 0x{last:04X}, {offset}),")
        offset += last - first + 1
    out.append("];")
    out.append("")
    out.append("/// One entry per code point in `BLOCKS`: 0 = no reading, else 1 + index into `SYLLABLES`.")
    out.append("#[rustfmt::skip]")
    out.append(f"pub(super) static INDEX: [u16; {total}] = [")
    for first, last in BLOCKS:
        for start in range(first, last + 1, PER_LINE):
            cps = range(start, min(start + PER_LINE, last + 1))
            nums = ",".join(str(index.get(reading.get(cp), 0)) for cp in cps)
            out.append(f"{nums}, // U+{start:04X}")
    out.append("];")

    here = os.path.dirname(os.path.abspath(__file__))
    dest = os.path.join(here, "..", "crates", "poni-core", "src", "romanize", "pinyin_data.rs")
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{dest}: {len(reading)} code points, {len(syllables)} syllables, {os.path.getsize(dest)} bytes")


if __name__ == "__main__":
    main()
