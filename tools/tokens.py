#!/usr/bin/env python3
"""Check design/tokens.json and write the site's design tokens from it.

Usage:
    python3 tools/tokens.py            # rewrite the token block in site/index.html
    python3 tools/tokens.py --check    # fail when the file is invalid or the block is out of date

design/tokens.json holds Oyenza Studio's design tokens: the website's colours,
fonts, radius and motion curves under "site", and Oyenza Studio Recorder's
theme under "recorder" (every entry there has a light and a dark value; a
colour without alpha is opaque). The
recorder keeps a pinned copy and generates its Rust constants from it
(apps/desktop-gpui/branding/tokens.py in oyen-studio-cap), so a change here
reaches the recorder only when that copy is synced.

On the site the tokens are CSS custom properties, written between the two
marker comments inside the first :root rule of site/index.html. Python 3
standard library only.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS = os.path.join(ROOT, "design", "tokens.json")
PAGE = os.path.join(ROOT, "site", "index.html")
START = "  /* design tokens: generated by tools/tokens.py from design/tokens.json */"
END = "  /* end of design tokens */"
COLOR = re.compile(r"#[0-9a-f]{6}([0-9a-f]{2})?")
LENGTH = re.compile(r"[0-9]+(\.[0-9]+)?px")
CURVE = re.compile(r"cubic-bezier\(-?[0-9.]+, -?[0-9.]+, -?[0-9.]+, -?[0-9.]+\)")
RECORDER_GROUPS = ("palette", "editor", "liquid-glass", "vibrancy")


def fail(message):
    sys.exit(f"design/tokens.json: {message}")


def check(tokens):
    if tokens.get("version") != 1:
        fail("unknown version (this script reads version 1)")
    site = tokens.get("site", {})
    for name, value in site.get("color", {}).items():
        if not isinstance(value, str) or not COLOR.fullmatch(value):
            fail(f"site.color.{name} is {value!r}, not a lowercase #rrggbb or #rrggbbaa colour")
    for name, value in site.get("font", {}).items():
        if not isinstance(value, str) or not value.strip():
            fail(f"site.font.{name} is empty")
    for name, value in site.get("radius", {}).items():
        if not isinstance(value, str) or not LENGTH.fullmatch(value):
            fail(f"site.radius.{name} is {value!r}, not a px length")
    for name, value in site.get("motion", {}).items():
        if not isinstance(value, str) or not CURVE.fullmatch(value):
            fail(f"site.motion.{name} is {value!r}, not a cubic-bezier()")
    recorder = tokens.get("recorder", {})
    if tuple(recorder) != RECORDER_GROUPS:
        fail(f"recorder groups are {list(recorder)}, expected {list(RECORDER_GROUPS)}")
    for group, entries in recorder.items():
        for name, modes in entries.items():
            if not isinstance(modes, dict) or set(modes) != {"light", "dark"}:
                fail(f"recorder.{group}.{name} needs exactly a light and a dark value")
            kinds = set()
            for mode, value in modes.items():
                if isinstance(value, str) and COLOR.fullmatch(value):
                    kinds.add("colour")
                elif isinstance(value, (int, float)) and not isinstance(value, bool):
                    kinds.add("number")
                else:
                    fail(f"recorder.{group}.{name}.{mode} is {value!r}, not a lowercase colour or a number")
            if len(kinds) != 1:
                fail(f"recorder.{group}.{name} mixes {sorted(kinds)}; light and dark must be the same kind")


def block(tokens):
    site = tokens["site"]
    lines = [START]
    lines += [f"  --{name}: {value};" for name, value in site["color"].items()]
    lines += [f"  --font-{name}: {value};" for name, value in site["font"].items()]
    lines += [f"  --{name}: {value};" for name, value in site["radius"].items()]
    lines += [f"  --{name}: {value};" for name, value in site["motion"].items()]
    lines.append(END)
    return "\n".join(lines)


def main():
    args = sys.argv[1:]
    if args not in ([], ["--check"]):
        sys.exit(__doc__)
    with open(TOKENS, encoding="utf-8") as f:
        tokens = json.load(f)
    check(tokens)
    with open(PAGE, encoding="utf-8") as f:
        page = f.read()
    if page.count(START) != 1 or page.count(END) != 1:
        sys.exit("site/index.html needs exactly one pair of design token markers inside :root")
    before, rest = page.split(START, 1)
    current, after = rest.split(END, 1)
    updated = before + block(tokens) + after
    if args == ["--check"]:
        if updated != page:
            sys.exit("site/index.html's design tokens are out of date: run python3 tools/tokens.py")
        print("design/tokens.json is valid and site/index.html matches it")
        return
    if updated != page:
        with open(PAGE, "w", encoding="utf-8") as f:
            f.write(updated)
        print("site/index.html: design tokens rewritten")
    else:
        print("site/index.html: design tokens already up to date")


if __name__ == "__main__":
    main()
