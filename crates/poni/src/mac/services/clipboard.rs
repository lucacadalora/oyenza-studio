//! Clipboard history on the Mac.
//!
//! The pasteboard has no change notification, so a light timer compares its
//! change count twice a second (an integer read; it never shows macOS's
//! paste alert) and reads the text only after a copy. Copies that ask not to
//! be recorded are skipped: password managers mark them concealed or
//! transient (the nspasteboard.org conventions 1Password, Bitwarden and
//! others follow), the same promise the Windows app keeps with its formats.
//! If the person set Oyen Poni's pasteboard access to "deny" (macOS 15.4+),
//! nothing is read at all.

use crate::events::{AppEvent, EventSink};
use block2::RcBlock;
use objc2::rc::Retained;
use objc2_app_kit::{NSPasteboard, NSPasteboardAccessBehavior, NSPasteboardTypeString};
use objc2_foundation::{NSRunLoop, NSRunLoopCommonModes, NSString, NSTimer};
use std::cell::Cell;
use std::ptr::NonNull;

/// Pasteboard types that mean "don't record this copy".
const PRIVATE_TYPES: [&str; 3] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
/// How often the change count is compared (seconds).
const POLL_S: f64 = 0.5;

pub struct Watcher {
    timer: Retained<NSTimer>,
}

impl Watcher {
    pub fn start(sink: EventSink) -> Watcher {
        let last = Cell::new(NSPasteboard::generalPasteboard().changeCount());
        let warned = Cell::new(false);
        let block = RcBlock::new(move |_t: NonNull<NSTimer>| {
            let pb = NSPasteboard::generalPasteboard();
            let n = pb.changeCount();
            if n == last.get() {
                return;
            }
            last.set(n);
            // `AlwaysDeny` (3): the person turned pasteboard access off for us.
            if pb.accessBehavior() == NSPasteboardAccessBehavior(3) {
                if !warned.replace(true) {
                    pinfo!("clipboard: access denied in System Settings; history paused");
                }
                return;
            }
            if is_private(&pb) {
                return;
            }
            if let Some(text) = pb.stringForType(unsafe { NSPasteboardTypeString }) {
                let text = text.to_string();
                if !text.trim().is_empty() {
                    sink.send(AppEvent::ClipboardText(text));
                }
            }
        });
        let timer = unsafe { NSTimer::timerWithTimeInterval_repeats_block(POLL_S, true, &block) };
        // Some slack lets macOS group the wake-ups with others (saves power).
        timer.setTolerance(0.2);
        unsafe { NSRunLoop::mainRunLoop().addTimer_forMode(&timer, NSRunLoopCommonModes) };
        Watcher { timer }
    }

    pub fn stop(self) {
        self.timer.invalidate();
    }
}

fn is_private(pb: &NSPasteboard) -> bool {
    let Some(types) = pb.types() else { return false };
    types.iter().any(|t| {
        let t = t.to_string();
        PRIVATE_TYPES.iter().any(|p| *p == t)
    })
}

/// Plain text on the clipboard (for paste into a text field).
pub fn read_text() -> Option<String> {
    let pb = NSPasteboard::generalPasteboard();
    let s = pb.stringForType(unsafe { NSPasteboardTypeString })?;
    Some(s.to_string())
}

/// Put text on the clipboard.
pub fn set_text(text: &str) {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    let _ = pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
}
